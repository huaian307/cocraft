def _hit(pattern: str, text: str) -> bool:
    """以 `NOT:` 开头 = 必须**不存在**（用来断言"旧的实现确实删干净了"）。"""
    if pattern.startswith("NOT:"):
        return re.search(pattern[4:], text) is None
    return re.search(pattern, text) is not None


